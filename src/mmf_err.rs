//! Public MMFErr (error handling) API.
//!
//! This API exposes the framework error handling
//! features.

use std::collections::VecDeque;
use std::sync::atomic::Ordering;
use chrono::{Utc, SecondsFormat};

use crate::module::EntityID;
use crate::framework_error::{FrameworkError, MMFPanic};
use crate::mmf::{MMF_ERR_DATA, MMF_ERR_NOTIFY, MMF_ERR_INSTANCE_COUNTER};
use crate::ModuleError;
use crate::string_helper;

/// Unique identifier assigned to each error event.
pub type ErrorInstanceID = u64;

/// Terminal error column widths.
mod terminal_error_column {

    pub const ERROR_ID_LEN: usize = 12;
    pub const TIME_LEN: usize = 12;
    pub const SENDER_ID_LEN: usize = 30;
    pub const MESSAGE_LEN: usize = 50;
    pub const SOURCE_LEN: usize = 50;
}

/// Error event recorded by MMFErr.
///
/// An ErrorEvent is generated whenever a module callback
/// (on_init, on_message or on_close) returns an error.
/// 
/// Error events are stored in a circular buffer and can
/// later be retrieved for diagnostics, logging or monitoring.
#[derive(Debug, Clone)]
pub struct ErrorEvent {

    /// Unique identifier assigned by MMFErr.
    pub error_instance_id: ErrorInstanceID,

    /// UTC timestamp when the error was recorded,
    /// formatted according to RFC 3339.
    pub timestamp_rfc3339: String,

    /// Origin of the error.
    pub sender_id: EntityID,

    /// Main error message returned by the module.
    pub error_message: String,

    /// Chain of underlying error causes.
    pub error_source_list: Vec<String>,
}

impl ErrorEvent {

    /// Converts the error event into a human-readable terminal string.
    fn to_terminal_string(&self) -> String {

        let root_error_source = string_helper::error_root_source(&self.error_source_list);
        format!(
            "{:0width_id$} | {:width_time$} | {:width_sender$} | {:width_message$} | {:width_source$}",
            self.error_instance_id,
            &self.timestamp_rfc3339[11..23],
            self.sender_id.to_short_string(terminal_error_column::SENDER_ID_LEN),
            string_helper::to_short_string(&self.error_message, terminal_error_column::MESSAGE_LEN),
            string_helper::to_short_string(&root_error_source, terminal_error_column::SOURCE_LEN),
            width_id = terminal_error_column::ERROR_ID_LEN,
            width_time = terminal_error_column::TIME_LEN,
            width_sender = terminal_error_column::SENDER_ID_LEN,
            width_message = terminal_error_column::MESSAGE_LEN,
            width_source = terminal_error_column::SOURCE_LEN,
        )
    }


    /// Converts the error event into a CSV row.
    fn to_csv_string(&self) -> String {

        let error_source_list = string_helper::error_source_list_to_string(&self.error_source_list);
        format!(
            "{},{},{},{},{}",
            self.error_instance_id,
            string_helper::csv_escape(&self.timestamp_rfc3339),
            string_helper::csv_escape(&self.sender_id.to_string()),
            string_helper::csv_escape(&self.error_message),
            string_helper::csv_escape(&error_source_list),
        )
    }
}

/// Internal MMFErr storage.
///
/// ErrorData maintains a circular buffer containing
/// the most recent error events generated by MMF.
#[derive(Debug, Clone)]
pub(crate) struct ErrorData {

    /// Capacity of error event buffer.
    pub(crate) error_event_buffer_capacity: usize,

    pub(crate) error_event_list: VecDeque<ErrorEvent>,
}

/// String output format.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum ErrorOutputFormat {

    /// Human-readable fixed-width table.
    Terminal,
    /// Comma-separated values.
    CSV,
}

/// Result returned by MMFErr::get_error_list().
///
/// This structure contains the error events requested
/// by the caller together with metadata describing
/// the state of the circular buffer.
#[derive(Debug, Clone)]
pub struct ErrorList {

    pub first_error_instance_id: Option<ErrorInstanceID>,

    pub last_error_instance_id: Option<ErrorInstanceID>,

    /// Number of events that could not be returned
    /// because they were overwritten in the circular buffer.
    pub missing_error_count: u64,

    pub error_event_list: Vec<ErrorEvent>,
}

impl ErrorList {

    /// Returns the column header corresponding to the requested format.
    pub fn get_header(format: ErrorOutputFormat) -> String {

        match format {

            ErrorOutputFormat::Terminal => {
                
                let header = format!(
                    "{:<width_id$} | {:<width_time$} | {:<width_sender$} | {:<width_message$} | {:<width_source$}",
                    "ErrorID",
                    "Time",
                    "SenderID",
                    "Message",
                    "Source",
                    width_id = terminal_error_column::ERROR_ID_LEN,
                    width_time = terminal_error_column::TIME_LEN,
                    width_sender = terminal_error_column::SENDER_ID_LEN,
                    width_message = terminal_error_column::MESSAGE_LEN,
                    width_source = terminal_error_column::SOURCE_LEN,
                );

                let separator = "-".repeat(header.len());
                format!("{header}\n{separator}")
                }

            ErrorOutputFormat::CSV => {
                
                String::from("ErrorID,Time,SenderID,Message,Source")
            }
        }
    }

    /// Converts all error events into strings.
    pub fn to_string_list(&self, format: ErrorOutputFormat) -> Vec<String> {

        match format {

            ErrorOutputFormat::Terminal => {

                self.error_event_list.iter().map(|error_event| error_event.to_terminal_string()).collect()
            }

            ErrorOutputFormat::CSV => {

                self.error_event_list.iter().map(|error_event| error_event.to_csv_string()).collect()
            }
        }
    }
}


pub struct MMFErr;

/// Public MMFErr entry point.
impl MMFErr {

    /// Generate a unique ErrorInstanceID.
    fn generate_error_instance_id() -> Result<u64, FrameworkError> {

        let current_id = MMF_ERR_INSTANCE_COUNTER.fetch_add(1, Ordering::Relaxed);
        if current_id == u64::MAX {
            return Err(FrameworkError::Error_InstanceIDExhausted);
        }

        Ok(current_id)
    }


    
    /// Record a new error event.
    ///
    /// This internal function is used by MMF to enrich error
    /// events with framework-specific context, such as the
    /// module callback where the error occurred.
    ///
    /// Application code should use `add_error()` instead.
    ///
    /// Error events are stored in a circular buffer and
    /// notify all MMFErr waiters.
    pub(crate) fn add_error_internal(sender_id: &EntityID, callback_name: Option<&'static str>, error: &ModuleError) -> Result<(), FrameworkError> {

        let error_instance_id = MMFErr::generate_error_instance_id()?;
        let error_message = error.to_string();

        let mut error_source_list = Vec::new();

        // Record the MMF callback that generated the error.
        if let Some(callback_name) = callback_name {
            error_source_list.push(callback_name.to_string());
        }

        let mut source = error.source();
        while let Some(error_source) = source {

            error_source_list.push(error_source.to_string());
            source = error_source.source();
        }
        
        let timestamp_rfc3339 = Utc::now().to_rfc3339_opts(SecondsFormat::Millis, true);

        let error_event = ErrorEvent {

            error_instance_id,
            timestamp_rfc3339,
            sender_id: sender_id.clone(),
            error_message,
            error_source_list,
        };

        // Maintain the error circular buffer.
        //
        // When the configured capacity is reached,
        // the oldest error events are discarded to make
        // room for newer ones.
        let mut mmf_err_data_guard = MMF_ERR_DATA.write().expect(MMFPanic::MMFErrData_WriteLockPoisoned.message());
        let mmf_err_data = mmf_err_data_guard.as_mut().ok_or(FrameworkError::Framework_NotInitialized)?;
        let error_event_buffer_capacity = mmf_err_data.error_event_buffer_capacity;
        
        while mmf_err_data.error_event_list.len() >= error_event_buffer_capacity {
            mmf_err_data.error_event_list.pop_front();
        }
        
        mmf_err_data.error_event_list.push_back(error_event);
        drop(mmf_err_data_guard);

        // Notify all waiters that a new error event
        // has been added to the buffer.
        MMF_ERR_NOTIFY.notify_waiters();

        Ok(())
    }


    /// Record a new application error event.
    ///
    /// This function allows application code to report
    /// custom errors through the MMFErr infrastructure.
    ///
    /// MMF internal errors are recorded through a dedicated
    /// internal API that automatically enriches the error
    /// context.
    ///
    /// Error events are stored in a circular buffer and
    /// notify all MMFErr waiters.
    pub fn add_error(sender_id: &EntityID, error: &ModuleError) -> Result<(), FrameworkError> {

        MMFErr::add_error_internal(&sender_id, None, error)
    }


    /// Wait until new error events are available.
    ///
    /// If last_error_instance_id is None, all error
    /// events currently stored in MMFErr are returned.
    ///
    /// If last_error_instance_id is provided, only
    /// events with a greater ErrorInstanceID are
    /// returned.
    ///
    /// If matching error events are already present
    /// in the MMFErr buffer, they are returned
    /// immediately without waiting.
    ///
    /// Returns Framework_NotInitialized if MMFErr
    /// has not been initialized through MMF::init().
    pub async fn wait_error(last_error_instance_id: Option<ErrorInstanceID>) -> Result<ErrorList, FrameworkError> {

        loop {

            let error_list = MMFErr::get_error_list(last_error_instance_id)?;

            // New error events are already available.
            //
            // Return immediately without waiting for a
            // notification.
            if !error_list.error_event_list.is_empty() {

                return Ok(error_list);
            }

            // No new error event is currently available.
            //
            // Wait until MMFErr is notified that a new
            // error event has been added.
            MMF_ERR_NOTIFY.notified().await;
        }
    }


    /// Retrieve error events stored in MMFErr.
    ///
    /// If last_error_instance_id is None,
    /// all events currently present in the circular
    /// buffer are returned.
    ///
    /// If last_error_instance_id is provided,
    /// only events with a greater ErrorInstanceID are
    /// returned.
    ///
    /// missing_error_count indicates how many events
    /// could not be returned because they were overwritten
    /// in the circular buffer before being retrieved.
    ///
    /// Returns Framework_NotInitialized if MMFErr has
    /// not been initialized through MMF::init().
    fn get_error_list(last_error_instance_id: Option<ErrorInstanceID>) -> Result<ErrorList, FrameworkError> {

        let mmf_err_data_guard = MMF_ERR_DATA.read().expect(MMFPanic::MMFErrData_ReadLockPoisoned.message());
        let mmf_err_data = mmf_err_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;
        
        // No error event is currently stored in MMFErr.
        if mmf_err_data.error_event_list.is_empty() {

            return Ok(
                ErrorList {

                    first_error_instance_id: None,
                    last_error_instance_id: None,
                    missing_error_count: 0,
                    error_event_list: Vec::new(),
                }
            );
        }

        // Retrieve the current boundaries of the circular buffer.
        //
        // The first and last ErrorInstanceID are used to detect
        // whether older events have been overwritten before
        // the caller could retrieve them.
        let first_error_event = mmf_err_data.error_event_list.front().expect(MMFPanic::ErrorBuffer_Inconsistency.message());
        let last_error_event =  mmf_err_data.error_event_list.back().expect(MMFPanic::ErrorBuffer_Inconsistency.message());

        let first_buffer_error_instance_id = first_error_event.error_instance_id;
        let last_buffer_error_instance_id = last_error_event.error_instance_id;

        // Determine how many events were missed by the caller.
        //
        // Missing events occur when the caller requests events
        // older than the first ErrorInstanceID currently present
        // in the circular buffer.
        let missing_error_count = match last_error_instance_id {

            None => 0,

            Some(last_seen) => {

                if last_seen >= last_buffer_error_instance_id {
                    0
                } else if last_seen < first_buffer_error_instance_id {
                    first_buffer_error_instance_id.saturating_sub(last_seen + 1)
                } else {
                    0
                }
            }
        };

        // Return only the events that have not yet been
        // received by the caller.
        let error_event_list = match last_error_instance_id {

            None => {

                mmf_err_data.error_event_list.iter().cloned().collect()
            }

            Some(last_seen) => {

                mmf_err_data.error_event_list.iter().filter(|error_event| {
                        error_event.error_instance_id > last_seen
                    }).cloned().collect()
            }
        };

        return Ok(
            ErrorList {

                first_error_instance_id: Some(first_buffer_error_instance_id),
                last_error_instance_id: Some(last_buffer_error_instance_id),
                missing_error_count,
                error_event_list,
            }
        );
    }

}