//! Public MWFErr (error handling) API.
//!
//! This API exposes the framework error handling
//! features.

use std::collections::VecDeque;
use std::sync::atomic::Ordering;
use tokio::sync::oneshot;
use tokio::task::JoinHandle;

use crate::MWF;
use crate::framework_error::{MWFError, MWFPanic};
use crate::mwf::{MWF_DATA, MWF_ERR_DATA, MWF_ERR_INSTANCE_COUNTER, MWF_ERR_NOTIFY, MWF_INSTANCE_COUNTER};
use crate::string_helper;
use crate::worker::EntityID;

/// Unique identifier assigned to each error event.
pub type ErrorInstanceID = u64;

/// Terminal error column widths.
mod terminal_error_column {

    pub const ERROR_ID_LEN: usize = 12;
    pub const TIME_LEN: usize = 12;
    pub const ERROR_SOURCE_ENTITY_ID_LEN: usize = 30;
    pub const ERROR_DESCRIPTION_LEN: usize = 50;
    pub const ERROR_CONTEXT_LEN: usize = 80;
}

/// Error event recorded by MWFErr.
///
/// An ErrorEvent is generated whenever a worker callback
/// (on_init, on_message or on_close) returns an error.
///
/// Error events are stored in a circular buffer and can
/// later be retrieved for diagnostics, logging or monitoring.
#[derive(Debug, Clone)]
pub struct ErrorEvent {
    /// Unique identifier assigned by MWFErr.
    pub error_instance_id: ErrorInstanceID,

    /// UTC timestamp when the error was recorded,
    /// formatted according to RFC 3339.
    pub timestamp_rfc3339: String,

    /// Origin of the error.
    pub entity_id: EntityID,

    /// Main error description returned by the worker.
    pub error_description: String,

    /// Chain of underlying error causes.
    pub error_context_list: Vec<String>,
}

impl ErrorEvent {
    /// Converts the error event into a human-readable terminal string.
    pub(crate) fn to_terminal_string(&self) -> String {
        let root_error_context = string_helper::error_root_context(&self.error_context_list);
        format!(
            "{:0width_id$} | {:width_time$} | {:width_entity_id$} | {:width_description$} | {:width_context$}",
            self.error_instance_id,
            &self.timestamp_rfc3339[11..23],
            self.entity_id.to_short_string(terminal_error_column::ERROR_SOURCE_ENTITY_ID_LEN),
            string_helper::to_short_string(&self.error_description, terminal_error_column::ERROR_DESCRIPTION_LEN),
            string_helper::to_short_string(&root_error_context, terminal_error_column::ERROR_CONTEXT_LEN),
            width_id = terminal_error_column::ERROR_ID_LEN,
            width_time = terminal_error_column::TIME_LEN,
            width_entity_id = terminal_error_column::ERROR_SOURCE_ENTITY_ID_LEN,
            width_description = terminal_error_column::ERROR_DESCRIPTION_LEN,
            width_context = terminal_error_column::ERROR_CONTEXT_LEN,
        )
    }

    /// Converts the error event into a CSV row.
    pub(crate) fn to_csv_string(&self) -> String {
        let error_context_list = string_helper::error_context_list_to_string(&self.error_context_list);
        format!("{},{},{},{},{}", self.error_instance_id, string_helper::csv_escape(&self.timestamp_rfc3339), string_helper::csv_escape(&self.entity_id.to_string()), string_helper::csv_escape(&self.error_description), string_helper::csv_escape(&error_context_list),)
    }
}

/// Internal MWFErr storage.
///
/// ErrorData maintains a circular buffer containing
/// the most recent error events generated by MWF.
#[derive(Debug)]
pub(crate) struct ErrorData {
    /// Capacity of error event buffer.
    pub(crate) error_event_buffer_capacity: usize,

    /// Circular buffer of error events.
    pub(crate) error_event_list: VecDeque<ErrorEvent>,

    /// Terminal error logging task activation.
    pub(crate) error_terminal_enabled: bool,

    /// Terminal error logging task handle.
    pub(crate) error_terminal_task_handle: Option<JoinHandle<()>>,

    /// Terminal error logging task shutdown sender.
    pub(crate) error_terminal_shutdown_sender: Option<oneshot::Sender<()>>,
}

/// String output format.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum ErrorOutputFormat {
    /// Human-readable fixed-width table.
    Terminal,
    /// Comma-separated values.
    CSV,
}

/// Result returned by MWFErr::get_error_list().
///
/// This structure contains the error events requested
/// by the caller together with metadata describing
/// the state of the circular buffer.
#[derive(Debug, Clone)]
pub struct ErrorList {
    pub first_error_instance_id: Option<ErrorInstanceID>,

    pub last_error_instance_id: Option<ErrorInstanceID>,

    /// Number of events that could not be returned
    /// because they were overwritten in the circular buffer.
    pub missing_error_count: u64,

    pub error_event_list: Vec<ErrorEvent>,
}

impl std::fmt::Display for ErrorList {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        writeln!(f)?;
        writeln!(f, "{}", Self::get_header(ErrorOutputFormat::Terminal))?;

        for line in self.to_string_list(ErrorOutputFormat::Terminal) {
            writeln!(f, "{line}")?;
        }
        Ok(())
    }
}

impl ErrorList {
    /// Returns the column header corresponding to the requested format.
    pub fn get_header(format: ErrorOutputFormat) -> String {
        match format {
            ErrorOutputFormat::Terminal => {
                let header = format!(
                    "{:<width_id$} | {:<width_time$} | {:<width_entity_id$} | {:<width_description$} | {:<width_context$}",
                    "ErrorID",
                    "Time",
                    "ErrorSource/EntityID",
                    "ErrorDescription",
                    "ErrorContext",
                    width_id = terminal_error_column::ERROR_ID_LEN,
                    width_time = terminal_error_column::TIME_LEN,
                    width_entity_id = terminal_error_column::ERROR_SOURCE_ENTITY_ID_LEN,
                    width_description = terminal_error_column::ERROR_DESCRIPTION_LEN,
                    width_context = terminal_error_column::ERROR_CONTEXT_LEN,
                );

                let separator = "-".repeat(header.len());
                format!("{header}\n{separator}")
            }

            ErrorOutputFormat::CSV => String::from("ErrorID,Time,ErrorSource/EntityID,ErrorDescription,ErrorContext"),
        }
    }

    /// Converts all error events into strings.
    pub fn to_string_list(&self, format: ErrorOutputFormat) -> Vec<String> {
        match format {
            ErrorOutputFormat::Terminal => self.error_event_list.iter().map(|error_event| error_event.to_terminal_string()).collect(),

            ErrorOutputFormat::CSV => self.error_event_list.iter().map(|error_event| error_event.to_csv_string()).collect(),
        }
    }
}

pub struct MWFErr;

/// Public MWFErr entry point.
impl MWFErr {
    /// Generate a unique ErrorInstanceID.
    fn generate_error_instance_id() -> Result<u64, MWFError> {
        MWF_ERR_INSTANCE_COUNTER.fetch_update(Ordering::Relaxed, Ordering::Relaxed, |current_id| current_id.checked_add(1)).map_err(|_| MWFError::Error_InstanceIDExhausted)
    }

    /// Record a new error event.
    ///
    /// This internal function is used by MWF to enrich error
    /// events with framework-specific context, such as the
    /// framework-specific context associated with the error.
    ///
    /// Application code should use `add_error()` instead.
    ///
    /// Error events are stored in a circular buffer and
    /// notify all MWFErr waiters.
    pub(crate) fn add_error_internal(entity_id: &EntityID, callback_name: Option<String>, error: &anyhow::Error) -> Result<(), MWFError> {
        let error_message = error.to_string();

        let mut error_context_list = Vec::new();

        // Record the MWF callback that generated the error.
        if let Some(callback_name) = callback_name {
            error_context_list.push(callback_name.to_string());
        }

        let mut context = error.source();
        while let Some(error_context) = context {
            error_context_list.push(error_context.to_string());
            context = error_context.source();
        }

        // Maintain the error circular buffer.
        //
        // When the configured capacity is reached,
        // the oldest error events are discarded to make
        // room for newer ones.
        let mut mwf_err_data_guard = MWF_ERR_DATA.write().expect(MWFPanic::MWFErrData_WriteLockPoisoned.message());
        let mwf_err_data = mwf_err_data_guard.as_mut().ok_or(MWFError::Framework_NotInitialized)?;

        let error_instance_id = MWFErr::generate_error_instance_id()?;
        let timestamp_rfc3339 = MWF::get_timestamp_rfc3339();
        let error_event = ErrorEvent { error_instance_id, timestamp_rfc3339, entity_id: entity_id.clone(), error_description: error_message, error_context_list };

        let error_event_buffer_capacity = mwf_err_data.error_event_buffer_capacity;

        while mwf_err_data.error_event_list.len() >= error_event_buffer_capacity {
            mwf_err_data.error_event_list.pop_front();
        }

        mwf_err_data.error_event_list.push_back(error_event);
        drop(mwf_err_data_guard);

        // Notify all waiters that a new error event
        // has been added to the buffer.
        MWF_ERR_NOTIFY.notify_waiters();

        Ok(())
    }

    /// Record a new application error event.
    ///
    /// This function allows application code to report
    /// custom errors through the MWFErr infrastructure.
    ///
    /// MWF internal errors are recorded through a dedicated
    /// internal API that automatically enriches the error
    /// context.
    ///
    /// Error events are stored in a circular buffer and
    /// notify all MWFErr waiters.
    pub fn add_error(error_source: &EntityID, error: &anyhow::Error) -> Result<(), MWFError> {
        // Ensure MWF is initialized and the current worker is still registered, when called from a worker context.
        drop(MWF::validate_api_context()?);

        // Validate the entity identifier.
        if !error_source.is_valid() {
            return Err(MWFError::Entity_Invalid { entity_id: error_source.clone() });
        }
        MWFErr::add_error_internal(error_source, None, error)
    }

    /// Wait until new error events are available.
    ///
    /// If last_error_instance_id is None, all error
    /// events currently stored in MWFErr are returned.
    ///
    /// If last_error_instance_id is provided, only
    /// events with a greater ErrorInstanceID are
    /// returned.
    ///
    /// If matching error events are already present
    /// in the MWFErr buffer, they are returned
    /// immediately without waiting.
    ///
    /// Returns `Ok(None)` if MWF is closed while waiting.
    /// Returns Framework_NotInitialized if called when MWF is already closed.
    pub async fn wait_error(last_error_instance_id: Option<ErrorInstanceID>) -> Result<Option<ErrorList>, MWFError> {
        let mwf_wrk_data_guard = MWF::validate_api_context()?;
        let mwf_instance_counter = MWF_INSTANCE_COUNTER.load(Ordering::Relaxed);
        drop(mwf_wrk_data_guard);

        match MWFErr::wait_error_internal(mwf_instance_counter, last_error_instance_id).await {
            Ok(error_list) => Ok(Some(error_list)),
            Err(MWFError::Framework_NotInitialized) => Ok(None),
            Err(error) => Err(error),
        }
    }

    // Waits for error events without validating the API context.
    // Used internally by the terminal error task during shutdown.
    async fn wait_error_internal(mwf_instance_counter: u64, last_error_instance_id: Option<ErrorInstanceID>) -> Result<ErrorList, MWFError> {
        loop {
            let error_notify = MWF_ERR_NOTIFY.notified();
            tokio::pin!(error_notify);
            error_notify.as_mut().enable();

            let error_list = MWFErr::get_error_list(mwf_instance_counter, last_error_instance_id)?;

            if !error_list.error_event_list.is_empty() {
                return Ok(error_list);
            }
            error_notify.await;
        }
    }

    /// Retrieve error events stored in MWFErr.
    ///
    /// If last_error_instance_id is None,
    /// all events currently present in the circular
    /// buffer are returned.
    ///
    /// If last_error_instance_id is provided,
    /// only events with a greater ErrorInstanceID are
    /// returned.
    ///
    /// missing_error_count indicates how many events
    /// could not be returned because they were overwritten
    /// in the circular buffer before being retrieved.
    ///
    /// Returns Framework_NotInitialized if MWFErr has
    /// not been initialized through MWF::init().
    fn get_error_list(mwf_instance_counter: u64, last_error_instance_id: Option<ErrorInstanceID>) -> Result<ErrorList, MWFError> {
        let mwf_err_data_guard = MWF_ERR_DATA.read().expect(MWFPanic::MWFErrData_ReadLockPoisoned.message());
        let mwf_err_data = mwf_err_data_guard.as_ref().ok_or(MWFError::Framework_NotInitialized)?;

        // Make sure the error buffer still belongs to the original MWF instance.
        if MWF_INSTANCE_COUNTER.load(Ordering::Relaxed) != mwf_instance_counter {
            return Err(MWFError::Framework_NotInitialized);
        }

        // No error event is currently stored in MWFErr.
        if mwf_err_data.error_event_list.is_empty() {
            return Ok(ErrorList { first_error_instance_id: None, last_error_instance_id: None, missing_error_count: 0, error_event_list: Vec::new() });
        }

        // Retrieve the current boundaries of the circular buffer.
        //
        // The first and last ErrorInstanceID are used to detect
        // whether older events have been overwritten before
        // the caller could retrieve them.
        let first_error_event = mwf_err_data.error_event_list.front().expect(MWFPanic::ErrorBuffer_Inconsistency.message());
        let last_error_event = mwf_err_data.error_event_list.back().expect(MWFPanic::ErrorBuffer_Inconsistency.message());

        let first_buffer_error_instance_id = first_error_event.error_instance_id;
        let last_buffer_error_instance_id = last_error_event.error_instance_id;

        // Determine how many events were missed by the caller.
        //
        // Missing events occur when the caller requests events
        // older than the first ErrorInstanceID currently present
        // in the circular buffer.
        let missing_error_count = match last_error_instance_id {
            None => 0,

            Some(last_seen) => {
                if last_seen >= last_buffer_error_instance_id {
                    0
                } else if last_seen < first_buffer_error_instance_id {
                    first_buffer_error_instance_id.saturating_sub(last_seen + 1)
                } else {
                    0
                }
            }
        };

        // Return only the events that have not yet been
        // received by the caller.
        let error_event_list = match last_error_instance_id {
            None => mwf_err_data.error_event_list.iter().cloned().collect(),

            Some(last_seen) => mwf_err_data.error_event_list.iter().filter(|error_event| error_event.error_instance_id > last_seen).cloned().collect(),
        };

        Ok(ErrorList { first_error_instance_id: Some(first_buffer_error_instance_id), last_error_instance_id: Some(last_buffer_error_instance_id), missing_error_count, error_event_list })
    }

    /// Enables or disables MWF terminal error logging.
    ///
    /// When enabled, MWF starts a background task that waits for new error events
    /// and prints them to the terminal.
    ///
    /// When disabled, the terminal error logging task is requested to stop, prints any
    /// remaining error events, and is awaited until it has fully terminated.
    pub async fn set_error_terminal_enabled(enabled: bool) -> Result<(), MWFError> {
        // Ensure MWF is initialized and the current worker is still registered, when called from a worker context.
        drop(MWF::validate_api_context()?);

        MWFErr::set_error_terminal_enabled_internal(enabled).await
    }

    /// Enables or disables terminal error logging for internal framework operations.
    ///
    /// Unlike the public API, this function does not validate the API context.
    /// It is intended for use by MWF internals, notably during framework shutdown.
    pub(crate) async fn set_error_terminal_enabled_internal(enabled: bool) -> Result<(), MWFError> {
        if enabled {
            // Prevent terminal error logging from being enabled while MWF is shutting down.
            let mwf_data_guard = MWF_DATA.read().expect(MWFPanic::MWFData_ReadLockPoisoned.message());
            if mwf_data_guard.is_none() {
                return Err(MWFError::Framework_NotInitialized);
            }

            let mwf_instance_counter = MWF_INSTANCE_COUNTER.load(Ordering::Relaxed);

            // Create a one-shot channel used to delay error consumption until the
            // terminal error logging task has been fully registered.
            let (start_sender, start_receiver) = oneshot::channel();

            // Create a one-shot channel used to request a graceful task shutdown.
            let (shutdown_sender, mut shutdown_receiver) = oneshot::channel();

            // Start the terminal error logging task before acquiring the MWF_ERR_DATA lock.
            let task_handle = tokio::spawn(async move {
                // Wait until the terminal error logging task has been fully registered.
                if start_receiver.await.is_err() {
                    return;
                }

                // Print the terminal error column header once when the logger starts.
                println!("{}", ErrorList::get_header(ErrorOutputFormat::Terminal));

                // Keep the last consumed error instance ID local to the logging task.
                let mut last_error_instance_id = None;

                loop {
                    tokio::select! {
                        error_result = MWFErr::wait_error_internal(mwf_instance_counter, last_error_instance_id) => {
                            match error_result {
                                Ok(error_list) => {
                                    // Print all newly received error events.
                                    for error_event in &error_list.error_event_list {
                                        println!("{}", error_event.to_terminal_string());
                                    }

                                    // Continue waiting from the last consumed error event.
                                    last_error_instance_id = error_list.last_error_instance_id;
                                }

                                Err(_) => {
                                    // Stop the terminal error logging task if MWF is no longer
                                    // available.
                                    return;
                                }
                            }
                        }

                        _ = &mut shutdown_receiver => {
                            // Print all error events that remain in the MWF error buffer.
                            if let Ok(error_list) = MWFErr::get_error_list(mwf_instance_counter, last_error_instance_id) {
                                for error_event in &error_list.error_event_list {
                                    println!("{}", error_event.to_terminal_string());
                                }
                            }

                            return;
                        }
                    }
                }
            });

            // Register the terminal error logging task before allowing it to consume errors.
            let mut mwf_err_data_guard = MWF_ERR_DATA.write().expect(MWFPanic::MWFErrData_WriteLockPoisoned.message());

            let error_data = match mwf_err_data_guard.as_mut() {
                Some(error_data) => error_data,
                None => {
                    // The task is still waiting for its start signal, so it can be
                    // safely aborted because it has not started consuming errors.
                    task_handle.abort();

                    return Err(MWFError::Framework_NotInitialized);
                }
            };

            // Ignore redundant enable requests.
            if error_data.error_terminal_enabled {
                // Another terminal error logging task is already active.
                task_handle.abort();

                return Ok(());
            }

            error_data.error_terminal_enabled = true;
            error_data.error_terminal_task_handle = Some(task_handle);
            error_data.error_terminal_shutdown_sender = Some(shutdown_sender);

            // The terminal error logging task is now fully registered and can start
            // consuming error events.
            let _ = start_sender.send(());

            drop(mwf_data_guard);
        } else {
            // Retrieve the terminal error logging task controls while updating its state.
            let (shutdown_sender, task_handle) = {
                let mut mwf_err_data_guard = MWF_ERR_DATA.write().expect(MWFPanic::MWFErrData_WriteLockPoisoned.message());

                let error_data = mwf_err_data_guard.as_mut().ok_or(MWFError::Framework_NotInitialized)?;

                // Ignore redundant disable requests.
                if !error_data.error_terminal_enabled {
                    return Ok(());
                }

                error_data.error_terminal_enabled = false;

                (error_data.error_terminal_shutdown_sender.take(), error_data.error_terminal_task_handle.take())
            };

            // Request the terminal error logging task to print its remaining error events
            // before terminating.
            if let Some(shutdown_sender) = shutdown_sender {
                let _ = shutdown_sender.send(());
            }

            // Wait until the terminal error logging task has printed all remaining errors
            // and terminated.
            if let Some(task_handle) = task_handle {
                task_handle.await.map_err(|error| MWFError::BlockingTask_Failed(anyhow::anyhow!(error)))?;
            }
        }

        Ok(())
    }
}
