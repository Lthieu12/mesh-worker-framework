/// Unique identifier assigned to each log event.
pub type LogInstanceID = u64;

/// Logging mode.
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogMode {
    /// Logging disabled.
    NoLog = 0,
    /// Log all workers.
    LogAll = 1,
    /// Log only selected workers.
    LogSelected = 2,
}

/// Log execution status.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogStatus {
    Start,
    Ok,
    Error,
}

/// Logged MWF action.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum LogAction {
    WorkerSpawn,
    WorkerInit,
    WorkerClose,
    WorkerAbort,
    WorkerPanic,
    WorkerMessage { message_instance_id: MessageInstanceID, sender_id: EntityID, message_id: MessageID, priority: bool, wait_completion: bool },
}

/// Internal MWFLog storage.
///
/// LoggingData maintains a circular buffer containing
/// the most recent logging events generated by MWF.
#[derive(Debug)]
pub(crate) struct LoggingData {
    /// Maximum number of log events retained.
    pub(crate) log_event_buffer_capacity: usize,

    /// Selected workers when LogSelected is active.
    pub(crate) logged_worker_list: Vec<WorkerID>,

    /// Circular buffer of log events.
    pub(crate) log_event_list: VecDeque<LogEvent>,

    /// mwf.log file activation.
    pub(crate) log_file_enabled: bool,

    /// mwf.log file path.
    pub(crate) log_file_path: Option<PathBuf>,

    /// mwf.log file reference.
    pub(crate) log_file: Option<File>,

    /// mwf.log file max size (bytes).
    pub(crate) log_file_max_size_bytes: u64,

    /// mwf.log file current size (bytes).
    pub(crate) log_file_current_size_bytes: u64,

    /// terminal log task activation.
    pub(crate) log_terminal_enabled: bool,

    /// Terminal logging task shutdown sender.
    pub(crate) log_terminal_shutdown_sender: Option<oneshot::Sender<()>>,

    /// terminal log task handle.
    pub(crate) log_terminal_task_handle: Option<JoinHandle<()>>,
}

/// Terminal log column widths.
mod terminal_log_column {

    pub(crate) const LOG_ID_LEN: usize = 12;
    pub(crate) const TIME_LEN: usize = 12;
    pub(crate) const WORKER_ID_LEN: usize = 30;
    pub(crate) const EVENT_LEN: usize = 7;
    pub(crate) const MESSAGE_ID_LEN: usize = 30;
    pub(crate) const SENDER_ID_LEN: usize = 30;
    pub(crate) const STATUS_LEN: usize = 6;
    pub(crate) const DURATION_LEN: usize = 8;
}

/// Single log event stored in MWFLog.
#[derive(Debug, Clone)]
pub struct LogEvent {
    /// Unique log identifier.
    pub log_instance_id: LogInstanceID,
    /// Event timestamp in RFC3339 format.
    pub timestamp_rfc3339: String,
    /// worker associated with the event.
    pub worker_id: WorkerID,
    /// Logged action.
    pub log_action: LogAction,
    /// Final action status.
    pub log_status: LogStatus,
    /// Action duration in milliseconds.
    pub duration_ms: Option<u128>,
}

impl LogEvent {
    /// Converts the log event into a human-readable terminal string.
    pub(crate) fn to_terminal_string(&self) -> String {
        let (event, sender_id, message_id, priority, wait) = match &self.log_action {
            LogAction::WorkerSpawn => ("SPAWN", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerInit => ("INIT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerClose => ("CLOSE", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerAbort => ("ABORT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerPanic => ("PANIC", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerMessage { message_instance_id: _, sender_id, message_id, priority, wait_completion } => {
                ("MESSAGE", sender_id.to_short_string(terminal_log_column::SENDER_ID_LEN), message_id.to_short_string(terminal_log_column::MESSAGE_ID_LEN), if *priority { "Y" } else { "N" }.to_string(), if *wait_completion { "Y" } else { "N" }.to_string())
            }
        };

        let duration = match self.duration_ms {
            Some(duration_ms) => format!("{duration_ms}ms"),
            None => "-".to_string(),
        };

        let status = match self.log_status {
            LogStatus::Start => "START",
            LogStatus::Ok => "OK",
            LogStatus::Error => "ERR",
        };

        format!(
            "{:0width_log$} | {:width_time$} | {:width_worker$} | {:width_event$} | {:width_message$} | {:width_sender$} | {} | {} | {:width_status$} | {:width_duration$}",
            self.log_instance_id,
            &self.timestamp_rfc3339[11..23],
            self.worker_id.to_short_string(terminal_log_column::WORKER_ID_LEN),
            event,
            message_id,
            sender_id,
            priority,
            wait,
            status,
            duration,
            width_log = terminal_log_column::LOG_ID_LEN,
            width_time = terminal_log_column::TIME_LEN,
            width_worker = terminal_log_column::WORKER_ID_LEN,
            width_event = terminal_log_column::EVENT_LEN,
            width_message = terminal_log_column::MESSAGE_ID_LEN,
            width_sender = terminal_log_column::SENDER_ID_LEN,
            width_status = terminal_log_column::STATUS_LEN,
            width_duration = terminal_log_column::DURATION_LEN,
        )
    }

    /// Converts the log event into a CSV row.
    pub(crate) fn to_csv_string(&self) -> String {
        let (event, message_instance_id, sender_id, message_id, priority, wait) = match &self.log_action {
            LogAction::WorkerSpawn => ("SPAWN", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerInit => ("INIT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerClose => ("CLOSE", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerAbort => ("ABORT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerPanic => ("PANIC", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::WorkerMessage { message_instance_id, sender_id, message_id, priority, wait_completion } => {
                ("MESSAGE", message_instance_id.to_string(), sender_id.to_string(), message_id.to_string(), if *priority { "Y" } else { "N" }.to_string(), if *wait_completion { "Y" } else { "N" }.to_string())
            }
        };

        let duration = match self.duration_ms {
            Some(duration_ms) => format!("{duration_ms}ms"),
            None => "-".to_string(),
        };

        let status = match self.log_status {
            LogStatus::Start => "START",
            LogStatus::Ok => "OK",
            LogStatus::Error => "ERR",
        };

        format!(
            "{},{},{},{},{},{},{},{},{},{},{}",
            self.log_instance_id,
            string_helper::csv_escape(&self.timestamp_rfc3339),
            string_helper::csv_escape(self.worker_id.as_str()),
            string_helper::csv_escape(event),
            string_helper::csv_escape(&message_instance_id),
            string_helper::csv_escape(&message_id),
            string_helper::csv_escape(&sender_id),
            string_helper::csv_escape(&priority),
            string_helper::csv_escape(&wait),
            string_helper::csv_escape(status),
            string_helper::csv_escape(&duration),
        )
    }
}

/// String output format.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogOutputFormat {
    /// Human-readable fixed-width table.
    Terminal,
    /// Comma-separated values.
    CSV,
}

/// Result returned by MWFErr::get_log_list().
///
/// This structure contains the log events requested
/// by the caller together with metadata describing
/// the state of the circular buffer.
#[derive(Debug, Clone)]
pub struct LogList {
    pub first_log_instance_id: Option<LogInstanceID>,

    pub last_log_instance_id: Option<LogInstanceID>,

    pub missing_log_count: u64,

    pub log_event_list: Vec<LogEvent>,
}

impl std::fmt::Display for LogList {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        writeln!(f)?;
        writeln!(f, "{}", Self::get_header(LogOutputFormat::Terminal))?;

        for line in self.to_string_list(LogOutputFormat::Terminal) {
            writeln!(f, "{line}")?;
        }
        Ok(())
    }
}

impl LogList {
    /// Returns the column header corresponding to the requested format.
    pub fn get_header(format: LogOutputFormat) -> String {
        match format {
            LogOutputFormat::Terminal => {
                let header = format!(
                    "{:<width_log$} | {:<width_time$} | {:<width_worker$} | {:<width_event$} | {:<width_message$} | {:<width_sender$} | P | W | {:<width_status$} | {:<width_duration$}",
                    "LogID",
                    "Time",
                    "WorkerID",
                    "Event",
                    "MessageID",
                    "SenderID",
                    "STATUS",
                    "Duration",
                    width_log = terminal_log_column::LOG_ID_LEN,
                    width_time = terminal_log_column::TIME_LEN,
                    width_worker = terminal_log_column::WORKER_ID_LEN,
                    width_event = terminal_log_column::EVENT_LEN,
                    width_message = terminal_log_column::MESSAGE_ID_LEN,
                    width_sender = terminal_log_column::SENDER_ID_LEN,
                    width_status = terminal_log_column::STATUS_LEN,
                    width_duration = terminal_log_column::DURATION_LEN,
                );

                let separator = "-".repeat(header.len());
                format!("{header}\n{separator}")
            }

            LogOutputFormat::CSV => String::from("LogID,Time,WorkerID,Event,MessageInstanceID,MessageID,SenderID,Priority,Wait,Status,Duration"),
        }
    }

    /// Converts all log events into strings.
    pub fn to_string_list(&self, format: LogOutputFormat) -> Vec<String> {
        match format {
            LogOutputFormat::Terminal => self.log_event_list.iter().map(|log_event| log_event.to_terminal_string()).collect(),

            LogOutputFormat::CSV => self.log_event_list.iter().map(|log_event| log_event.to_csv_string()).collect(),
        }
    }
}

pub struct MWFLog;

/// Public MWFLog entry point.
impl MWFLog {
    /// Change the current MWF logging mode.
    ///
    /// When LogSelected is used, the provided worker list
    /// replaces the previously configured selection.
    ///
    /// Returns Framework_NotInitialized if MWF has not
    /// been initialized through MWF::init().
    pub fn set_log_mode(log_mode: LogMode, logged_worker_list: Option<Vec<WorkerID>>) -> Result<(), MWFError> {
        let mut mwf_log_data_guard = MWF_LOG_DATA.write().expect(MWFPanic::MWFLogData_WriteLockPoisoned.message());
        let mwf_log_data = mwf_log_data_guard.as_mut().ok_or(MWFError::Framework_NotInitialized)?;

        MWF_LOG_MODE.store(log_mode as u8, Ordering::Relaxed);

        if let Some(logged_worker_list) = logged_worker_list {
            mwf_log_data.logged_worker_list = logged_worker_list;
        }

        drop(mwf_log_data_guard);
        Ok(())
    }

    /// Retrieve the current MWF logging mode.
    ///
    /// Returns Framework_NotInitialized if MWF has not
    /// been initialized through MWF::init().
    pub fn get_log_mode() -> Result<LogMode, MWFError> {
        let mwf_log_data_guard = MWF_LOG_DATA.read().expect(MWFPanic::MWFLogData_ReadLockPoisoned.message());

        if mwf_log_data_guard.is_none() {
            return Err(MWFError::Framework_NotInitialized);
        }

        let log_mode = match MWF_LOG_MODE.load(Ordering::Relaxed) {
            0 => LogMode::NoLog,
            1 => LogMode::LogAll,
            2 => LogMode::LogSelected,
            // Invalid value => NoLog
            _ => LogMode::NoLog,
        };

        drop(mwf_log_data_guard);
        Ok(log_mode)
    }

    /// Retrieve the currently selected worker list.
    ///
    /// Returns Framework_NotInitialized if MWF has not
    /// been initialized through MWF::init().
    pub fn get_logged_worker_list() -> Result<Vec<WorkerID>, MWFError> {
        let mwf_log_data_guard = MWF_LOG_DATA.read().expect(MWFPanic::MWFLogData_ReadLockPoisoned.message());
        let mwf_log_data = mwf_log_data_guard.as_ref().ok_or(MWFError::Framework_NotInitialized)?;
        let logged_worker_list = mwf_log_data.logged_worker_list.clone();

        drop(mwf_log_data_guard);
        Ok(logged_worker_list)
    }

    /// Remove a worker from the MWFLog selected worker list.
    ///
    /// If the worker is not currently present in the
    /// selected worker list, this function does nothing.
    ///
    /// Returns Framework_NotInitialized if MWF has not
    /// been initialized through MWF::init().
    pub(crate) fn remove_logged_worker(worker_id: &WorkerID) -> Result<(), MWFError> {
        let mut mwf_log_data_guard = MWF_LOG_DATA.write().expect(MWFPanic::MWFLogData_WriteLockPoisoned.message());
        let mwf_log_data = mwf_log_data_guard.as_mut().ok_or(MWFError::Framework_NotInitialized)?;
        mwf_log_data.logged_worker_list.retain(|logged_worker_id| logged_worker_id != worker_id);
        drop(mwf_log_data_guard);

        Ok(())
    }

    /// Generate a unique LogInstanceID.
    fn generate_log_instance_id() -> Result<u64, MWFError> {
        let current_id = MWF_LOG_INSTANCE_COUNTER.fetch_add(1, Ordering::Relaxed);
        if current_id == u64::MAX {
            return Err(MWFError::Logging_InstanceIDExhausted);
        }

        Ok(current_id)
    }

    /// Check whether logging is enabled for a worker.
    pub(crate) fn must_log_worker(worker_id: &WorkerID) -> Result<bool, MWFError> {
        let log_mode = MWF_LOG_MODE.load(Ordering::Relaxed);

        if log_mode == LogMode::NoLog as u8 {
            return Ok(false);
        }

        if log_mode == LogMode::LogAll as u8 {
            return Ok(true);
        }

        if log_mode == LogMode::LogSelected as u8 {
            let mwf_log_data_guard = MWF_LOG_DATA.read().expect(MWFPanic::MWFLogData_ReadLockPoisoned.message());
            let logging_data = mwf_log_data_guard.as_ref().ok_or(MWFError::Framework_NotInitialized)?;
            return Ok(logging_data.logged_worker_list.iter().any(|logged_worker_id| logged_worker_id == worker_id));
        }

        // Invalid value => NoLog
        Ok(false)
    }

    /// Add a log event to MWFLog.
    ///
    /// If logging is disabled for the specified worker,
    /// the event is silently ignored.
    ///
    /// Returns Framework_NotInitialized if MWF has
    /// not been initialized through MWF::init().
    pub(crate) fn add_log(action_start_timer: Instant, worker_id: &WorkerID, log_action: LogAction, log_status: LogStatus) -> Result<(), MWFError> {
        // Skip immediately if logging is disabled
        // for this worker.
        if !Self::must_log_worker(worker_id)? {
            return Ok(());
        }

        let duration_ms: Option<u128> = match log_status {
            LogStatus::Start => None,

            LogStatus::Ok | LogStatus::Error => Some(action_start_timer.elapsed().as_millis()),
        };

        let mut mwf_log_data_guard = MWF_LOG_DATA.write().expect(MWFPanic::MWFLogData_WriteLockPoisoned.message());
        let logging_data = mwf_log_data_guard.as_mut().ok_or(MWFError::Framework_NotInitialized)?;

        let log_instance_id = MWFLog::generate_log_instance_id()?;
        let timestamp_rfc3339 = MWF::get_timestamp_rfc3339();
        let log_event = LogEvent { log_instance_id, timestamp_rfc3339, worker_id: worker_id.to_owned(), log_action, log_status, duration_ms };

        // Write the log event to the log file if enabled.
        write_log_event(logging_data, &log_event)?;

        // Circular buffer behavior.
        if logging_data.log_event_list.len() >= logging_data.log_event_buffer_capacity {
            logging_data.log_event_list.pop_front();
        }
        logging_data.log_event_list.push_back(log_event);

        drop(mwf_log_data_guard);

        // Notify all waiters that a new log event
        // has been added to the buffer.
        MWF_LOG_NOTIFY.notify_waiters();

        Ok(())
    }

    /// Wait until new log events are available.
    ///
    /// If last_log_instance_id is None, all log
    /// events currently stored in MWFLog are returned.
    ///
    /// If last_log_instance_id is provided, only
    /// events with a greater LogInstanceID are
    /// returned.
    ///
    /// If matching log events are already present
    /// in the MWFLog buffer, they are returned
    /// immediately without waiting.
    ///
    /// Returns Framework_NotInitialized if MWFLog
    /// has not been initialized through MWF::init().
    pub async fn wait_log(last_log_instance_id: Option<LogInstanceID>) -> Result<LogList, MWFError> {
        loop {
            let log_list = MWFLog::get_log_list(last_log_instance_id)?;

            // New log events are already available.
            //
            // Return immediately without waiting for a
            // notification.
            if !log_list.log_event_list.is_empty() {
                return Ok(log_list);
            }

            // No new log event is currently available.
            //
            // Wait until MWFLog is notified that a new
            // log event has been added.
            MWF_LOG_NOTIFY.notified().await;
        }
    }

    /// Retrieve log events stored in MWFLog.
    ///
    /// If last_log_instance_id is None,
    /// all events currently present in the circular
    /// buffer are returned.
    ///
    /// If last_log_instance_id is provided,
    /// only events with a greater LogInstanceID are
    /// returned.
    ///
    /// missing_log_count indicates how many events
    /// could not be returned because they were overwritten
    /// in the circular buffer before being retrieved.
    ///
    /// Returns Framework_NotInitialized if MWFLog has
    /// not been initialized through MWF::init().
    fn get_log_list(last_log_instance_id: Option<LogInstanceID>) -> Result<LogList, MWFError> {
        let mwf_log_data_guard = MWF_LOG_DATA.read().expect(MWFPanic::MWFLogData_ReadLockPoisoned.message());
        let mwf_log_data = mwf_log_data_guard.as_ref().ok_or(MWFError::Framework_NotInitialized)?;

        // No log event is currently stored in MWFLog.
        if mwf_log_data.log_event_list.is_empty() {
            return Ok(LogList { first_log_instance_id: None, last_log_instance_id: None, missing_log_count: 0, log_event_list: Vec::new() });
        }

        // Retrieve the current boundaries of the circular buffer.
        //
        // The first and last LogInstanceID are used to detect
        // whether older events have been overwritten before
        // the caller could retrieve them.
        let first_log_event = mwf_log_data.log_event_list.front().expect(MWFPanic::LogBuffer_Inconsistency.message());
        let last_log_event = mwf_log_data.log_event_list.back().expect(MWFPanic::LogBuffer_Inconsistency.message());

        let first_buffer_log_instance_id = first_log_event.log_instance_id;
        let last_buffer_log_instance_id = last_log_event.log_instance_id;

        // Determine how many events were missed by the caller.
        //
        // Missing events occur when the caller requests events
        // older than the first LogInstanceID currently present
        // in the circular buffer.
        let missing_log_count = match last_log_instance_id {
            None => 0,

            Some(last_seen) => {
                if last_seen >= last_buffer_log_instance_id {
                    0
                } else if last_seen < first_buffer_log_instance_id {
                    first_buffer_log_instance_id.saturating_sub(last_seen + 1)
                } else {
                    0
                }
            }
        };

        // Return only the events that have not yet been
        // received by the caller.
        let log_event_list = match last_log_instance_id {
            None => mwf_log_data.log_event_list.iter().cloned().collect(),

            Some(last_seen) => mwf_log_data.log_event_list.iter().filter(|log_event| log_event.log_instance_id > last_seen).cloned().collect(),
        };

        Ok(LogList { first_log_instance_id: Some(first_buffer_log_instance_id), last_log_instance_id: Some(last_buffer_log_instance_id), missing_log_count, log_event_list })
    }

    /// Enables or disables MWF file logging.
    ///
    /// When enabled, every log event is immediately written to the log file
    /// and flushed to disk. This improves crash diagnostics, especially for
    /// native DLL failures, but introduces additional disk I/O and may reduce
    /// overall framework performance.
    pub fn set_log_file_enabled(enabled: bool) -> Result<(), MWFError> {
        let mut mwf_log_data_guard = MWF_LOG_DATA.write().expect(MWFPanic::MWFLogData_WriteLockPoisoned.message());

        let logging_data = mwf_log_data_guard.as_mut().ok_or(MWFError::Framework_NotInitialized)?;

        if enabled && logging_data.log_file_path.is_none() {
            return Err(MWFError::Logging_LogFileNotConfigured);
        }

        logging_data.log_file_enabled = enabled;

        Ok(())
    }

    /// Returns the current MWF log file path.
    pub fn get_log_file_path() -> Result<Option<PathBuf>, MWFError> {
        let mwf_log_data_guard = MWF_LOG_DATA.read().expect(MWFPanic::MWFLogData_ReadLockPoisoned.message());

        let logging_data = mwf_log_data_guard.as_ref().ok_or(MWFError::Framework_NotInitialized)?;

        Ok(logging_data.log_file_path.clone())
    }

    /// Enables or disables MWF terminal logging.
    ///
    /// When enabled, MWF starts a background task that waits for new log events
    /// and prints them to the terminal.
    ///
    /// When disabled, the terminal logging task is requested to stop, prints any
    /// remaining log events, and is awaited until it has fully terminated.
    pub async fn set_log_terminal_enabled(enabled: bool) -> Result<(), MWFError> {
        if enabled {
            // Create a one-shot channel used to delay log consumption until the
            // terminal logging task has been fully registered.
            let (start_sender, start_receiver) = oneshot::channel();

            // Create a one-shot channel used to request a graceful task shutdown.
            let (shutdown_sender, mut shutdown_receiver) = oneshot::channel();

            // Start the terminal logging task before acquiring the MWF_LOG_DATA lock.
            let task_handle = tokio::spawn(async move {
                // Wait until the terminal logging task has been fully registered.
                if start_receiver.await.is_err() {
                    return;
                }

                // Print the terminal log column header once when the logger starts.
                println!("{}", LogList::get_header(LogOutputFormat::Terminal));

                // Keep the last consumed log instance ID local to the logging task.
                let mut last_log_instance_id = None;

                loop {
                    tokio::select! {
                        log_result = MWFLog::wait_log(last_log_instance_id) => {
                            match log_result {
                                Ok(log_list) => {
                                    // Print all newly received log events.
                                    for log_event in &log_list.log_event_list {
                                        println!("{}", log_event.to_terminal_string());
                                    }

                                    // Continue waiting from the last consumed log event.
                                    last_log_instance_id = log_list.last_log_instance_id;
                                }

                                Err(_) => {
                                    // Stop the terminal logging task if MWF is no longer
                                    // available.
                                    return;
                                }
                            }
                        }

                        _ = &mut shutdown_receiver => {
                            // Print all log events that remain in the MWF log buffer.
                            if let Ok(log_list) = MWFLog::get_log_list(last_log_instance_id) {
                                for log_event in &log_list.log_event_list {
                                    println!("{}", log_event.to_terminal_string());
                                }
                            }

                            return;
                        }
                    }
                }
            });

            // Register the terminal logging task before allowing it to consume logs.
            let mut mwf_log_data_guard = MWF_LOG_DATA.write().expect(MWFPanic::MWFLogData_WriteLockPoisoned.message());

            let logging_data = match mwf_log_data_guard.as_mut() {
                Some(logging_data) => logging_data,
                None => {
                    // The task is still waiting for its start signal, so it can be
                    // safely aborted because it has not started consuming logs.
                    task_handle.abort();

                    return Err(MWFError::Framework_NotInitialized);
                }
            };

            // Ignore redundant enable requests.
            if logging_data.log_terminal_enabled {
                // Another terminal logging task is already active.
                task_handle.abort();

                return Ok(());
            }

            logging_data.log_terminal_enabled = true;
            logging_data.log_terminal_task_handle = Some(task_handle);
            logging_data.log_terminal_shutdown_sender = Some(shutdown_sender);

            // The terminal logging task is now fully registered and can start
            // consuming log events.
            let _ = start_sender.send(());
        } else {
            // Retrieve the terminal logging task controls while updating its state.
            let (shutdown_sender, task_handle) = {
                let mut mwf_log_data_guard = MWF_LOG_DATA.write().expect(MWFPanic::MWFLogData_WriteLockPoisoned.message());

                let logging_data = mwf_log_data_guard.as_mut().ok_or(MWFError::Framework_NotInitialized)?;

                // Ignore redundant disable requests.
                if !logging_data.log_terminal_enabled {
                    return Ok(());
                }

                logging_data.log_terminal_enabled = false;

                (logging_data.log_terminal_shutdown_sender.take(), logging_data.log_terminal_task_handle.take())
            };

            // Request the terminal logging task to print its remaining log events
            // before terminating.
            if let Some(shutdown_sender) = shutdown_sender {
                let _ = shutdown_sender.send(());
            }

            // Wait until the terminal logging task has printed all remaining logs
            // and terminated.
            if let Some(task_handle) = task_handle {
                let _ = task_handle.await;
            }
        }

        Ok(())
    }
}
