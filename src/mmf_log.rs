//! Public MMFLog (logging and observability) API.
//!
//! This API exposes the framework logging and observability
//! features.

use std::collections::VecDeque;
use std::fs::File;
use std::path::PathBuf;
use std::sync::atomic::Ordering;
use std::time::Instant;

use crate::MMF;
use crate::framework_error::{FrameworkError, MMFPanic};
use crate::log_file::write_log_event;
use crate::message::{MessageID, MessageInstanceID};
use crate::mmf::{MMF_LOG_DATA, MMF_LOG_INSTANCE_COUNTER, MMF_LOG_MODE, MMF_LOG_NOTIFY};
use crate::module::{EntityID, ModuleID};
use crate::string_helper;

/// Unique identifier assigned to each log event.
pub type LogInstanceID = u64;

/// Logging mode.
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogMode {
    /// Logging disabled.
    NoLog = 0,
    /// Log all modules.
    LogAll = 1,
    /// Log only selected modules.
    LogSelected = 2,
}

/// Log execution status.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogStatus {
    Start,
    Ok,
    Error,
}

/// Logged MMF action.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum LogAction {
    ModuleSpawn,
    ModuleInit,
    ModuleClose,
    ModuleAbort,
    ModulePanic,
    ModuleMessage { message_instance_id: MessageInstanceID, sender_id: EntityID, message_id: MessageID, priority: bool, wait_completion: bool },
}

/// Internal MMFLog storage.
///
/// LoggingData maintains a circular buffer containing
/// the most recent logging events generated by MMF.
#[derive(Debug)]
pub(crate) struct LoggingData {
    /// Maximum number of log events retained.
    pub(crate) log_event_buffer_capacity: usize,

    /// Selected modules when LogSelected is active.
    pub(crate) logged_module_list: Vec<ModuleID>,

    /// Circular buffer of log events.
    pub(crate) log_event_list: VecDeque<LogEvent>,

    /// mmf.log file activation
    pub(crate) log_file_enabled: bool,

    /// mmf.log file path
    pub(crate) log_file_path: PathBuf,

    /// mmf.log file reference
    pub(crate) log_file: Option<File>,

    /// mmf.log file max size (bytes)
    pub(crate) log_file_max_size_bytes: u64,

    /// mmf.log file current size (bytes)
    pub(crate) log_file_current_size_bytes: u64,
}

/// Terminal log column widths.
mod terminal_log_column {

    pub(crate) const LOG_ID_LEN: usize = 12;
    pub(crate) const TIME_LEN: usize = 12;
    pub(crate) const MODULE_ID_LEN: usize = 30;
    pub(crate) const EVENT_LEN: usize = 7;
    pub(crate) const MESSAGE_ID_LEN: usize = 30;
    pub(crate) const SENDER_ID_LEN: usize = 30;
    pub(crate) const STATUS_LEN: usize = 6;
    pub(crate) const DURATION_LEN: usize = 8;
}

/// Single log event stored in MMFLog.
#[derive(Debug, Clone)]
pub struct LogEvent {
    /// Unique log identifier.
    pub log_instance_id: LogInstanceID,
    /// Event timestamp in RFC3339 format.
    pub timestamp_rfc3339: String,
    /// Module associated with the event.
    pub module_id: ModuleID,
    /// Logged action.
    pub log_action: LogAction,
    /// Final action status.
    pub log_status: LogStatus,
    /// Action duration in milliseconds.
    pub duration_ms: Option<u128>,
}

impl LogEvent {
    /// Converts the log event into a human-readable terminal string.
    pub(crate) fn to_terminal_string(&self) -> String {
        let (event, sender_id, message_id, priority, wait) = match &self.log_action {
            LogAction::ModuleSpawn => ("SPAWN", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleInit => ("INIT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleClose => ("CLOSE", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleAbort => ("ABORT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModulePanic => ("PANIC", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleMessage { message_instance_id: _, sender_id, message_id, priority, wait_completion } => {
                ("MESSAGE", sender_id.to_short_string(terminal_log_column::SENDER_ID_LEN), string_helper::to_short_string(&message_id.clone(), terminal_log_column::MESSAGE_ID_LEN), if *priority { "Y" } else { "N" }.to_string(), if *wait_completion { "Y" } else { "N" }.to_string())
            }
        };

        let duration = match self.duration_ms {
            Some(duration_ms) => format!("{duration_ms}ms"),
            None => "-".to_string(),
        };

        let status = match self.log_status {
            LogStatus::Start => "START",
            LogStatus::Ok => "OK",
            LogStatus::Error => "ERR",
        };

        format!(
            "{:0width_log$} | {:width_time$} | {:width_module$} | {:width_event$} | {:width_message$} | {:width_sender$} | {} | {} | {:width_status$} | {:width_duration$}",
            self.log_instance_id,
            &self.timestamp_rfc3339[11..23],
            EntityID::Module(self.module_id.clone()).to_short_string(terminal_log_column::MODULE_ID_LEN),
            event,
            message_id,
            sender_id,
            priority,
            wait,
            status,
            duration,
            width_log = terminal_log_column::LOG_ID_LEN,
            width_time = terminal_log_column::TIME_LEN,
            width_module = terminal_log_column::MODULE_ID_LEN,
            width_event = terminal_log_column::EVENT_LEN,
            width_message = terminal_log_column::MESSAGE_ID_LEN,
            width_sender = terminal_log_column::SENDER_ID_LEN,
            width_status = terminal_log_column::STATUS_LEN,
            width_duration = terminal_log_column::DURATION_LEN,
        )
    }

    /// Converts the log event into a CSV row.
    pub(crate) fn to_csv_string(&self) -> String {
        let (event, message_instance_id, sender_id, message_id, priority, wait) = match &self.log_action {
            LogAction::ModuleSpawn => ("SPAWN", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleInit => ("INIT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleClose => ("CLOSE", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleAbort => ("ABORT", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModulePanic => ("PANIC", "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string(), "-".to_string()),
            LogAction::ModuleMessage { message_instance_id, sender_id, message_id, priority, wait_completion } => {
                ("MESSAGE", message_instance_id.to_string(), sender_id.to_string(), message_id.clone(), if *priority { "Y" } else { "N" }.to_string(), if *wait_completion { "Y" } else { "N" }.to_string())
            }
        };

        let duration = match self.duration_ms {
            Some(duration_ms) => format!("{duration_ms}ms"),
            None => "-".to_string(),
        };

        let status = match self.log_status {
            LogStatus::Start => "START",
            LogStatus::Ok => "OK",
            LogStatus::Error => "ERR",
        };

        format!(
            "{},{},{},{},{},{},{},{},{},{},{}",
            self.log_instance_id,
            string_helper::csv_escape(&self.timestamp_rfc3339),
            string_helper::csv_escape(self.module_id.as_str()),
            string_helper::csv_escape(event),
            string_helper::csv_escape(&message_instance_id),
            string_helper::csv_escape(&message_id),
            string_helper::csv_escape(&sender_id),
            string_helper::csv_escape(&priority),
            string_helper::csv_escape(&wait),
            string_helper::csv_escape(status),
            string_helper::csv_escape(&duration),
        )
    }
}

/// String output format.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogOutputFormat {
    /// Human-readable fixed-width table.
    Terminal,
    /// Comma-separated values.
    CSV,
}

/// Result returned by MMFErr::get_log_list().
///
/// This structure contains the log events requested
/// by the caller together with metadata describing
/// the state of the circular buffer.
#[derive(Debug, Clone)]
pub struct LogList {
    pub first_log_instance_id: Option<LogInstanceID>,

    pub last_log_instance_id: Option<LogInstanceID>,

    pub missing_log_count: u64,

    pub log_event_list: Vec<LogEvent>,
}

impl std::fmt::Display for LogList {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        writeln!(f)?;
        writeln!(f, "{}", Self::get_header(LogOutputFormat::Terminal))?;

        for line in self.to_string_list(LogOutputFormat::Terminal) {
            writeln!(f, "{line}")?;
        }
        Ok(())
    }
}

impl LogList {
    /// Returns the column header corresponding to the requested format.
    pub fn get_header(format: LogOutputFormat) -> String {
        match format {
            LogOutputFormat::Terminal => {
                let header = format!(
                    "{:<width_log$} | {:<width_time$} | {:<width_module$} | {:<width_event$} | {:<width_message$} | {:<width_sender$} | P | W | {:<width_status$} | {:<width_duration$}",
                    "LogID",
                    "Time",
                    "ModuleID",
                    "Event",
                    "MessageID",
                    "SenderID",
                    "STATUS",
                    "Duration",
                    width_log = terminal_log_column::LOG_ID_LEN,
                    width_time = terminal_log_column::TIME_LEN,
                    width_module = terminal_log_column::MODULE_ID_LEN,
                    width_event = terminal_log_column::EVENT_LEN,
                    width_message = terminal_log_column::MESSAGE_ID_LEN,
                    width_sender = terminal_log_column::SENDER_ID_LEN,
                    width_status = terminal_log_column::STATUS_LEN,
                    width_duration = terminal_log_column::DURATION_LEN,
                );

                let separator = "-".repeat(header.len());
                format!("{header}\n{separator}")
            }

            LogOutputFormat::CSV => String::from("LogID,Time,ModuleID,Event,MessageInstanceID,MessageID,SenderID,Priority,Wait,Status,Duration"),
        }
    }

    /// Converts all log events into strings.
    pub fn to_string_list(&self, format: LogOutputFormat) -> Vec<String> {
        match format {
            LogOutputFormat::Terminal => self.log_event_list.iter().map(|log_event| log_event.to_terminal_string()).collect(),

            LogOutputFormat::CSV => self.log_event_list.iter().map(|log_event| log_event.to_csv_string()).collect(),
        }
    }
}

pub struct MMFLog;

/// Public MMFLog entry point.
impl MMFLog {
    /// Change the current MMF logging mode.
    ///
    /// When LogSelected is used, the provided module list
    /// replaces the previously configured selection.
    ///
    /// Returns Framework_NotInitialized if MMF has not
    /// been initialized through MMF::init().
    pub fn set_log_mode(log_mode: LogMode, logged_module_list: Option<Vec<ModuleID>>) -> Result<(), FrameworkError> {
        let mut mmf_log_data_guard = MMF_LOG_DATA.write().expect(MMFPanic::MMFLogData_WriteLockPoisoned.message());
        let mmf_log_data = mmf_log_data_guard.as_mut().ok_or(FrameworkError::Framework_NotInitialized)?;

        MMF_LOG_MODE.store(log_mode as u8, Ordering::Relaxed);

        if let Some(logged_module_list) = logged_module_list {
            mmf_log_data.logged_module_list = logged_module_list;
        }

        drop(mmf_log_data_guard);
        Ok(())
    }

    /// Retrieve the current MMF logging mode.
    ///
    /// Returns Framework_NotInitialized if MMF has not
    /// been initialized through MMF::init().
    pub fn get_log_mode() -> Result<LogMode, FrameworkError> {
        let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());

        if mmf_log_data_guard.is_none() {
            return Err(FrameworkError::Framework_NotInitialized);
        }

        let log_mode = match MMF_LOG_MODE.load(Ordering::Relaxed) {
            0 => LogMode::NoLog,
            1 => LogMode::LogAll,
            2 => LogMode::LogSelected,
            // Invalid value => NoLog
            _ => LogMode::NoLog,
        };

        drop(mmf_log_data_guard);
        Ok(log_mode)
    }

    /// Retrieve the currently selected module list.
    ///
    /// Returns Framework_NotInitialized if MMF has not
    /// been initialized through MMF::init().
    pub fn get_logged_module_list() -> Result<Vec<ModuleID>, FrameworkError> {
        let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());
        let mmf_log_data = mmf_log_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;
        let logged_module_list = mmf_log_data.logged_module_list.clone();

        drop(mmf_log_data_guard);
        Ok(logged_module_list)
    }

    /// Remove a module from the MMFLog selected module list.
    ///
    /// If the module is not currently present in the
    /// selected module list, this function does nothing.
    ///
    /// Returns Framework_NotInitialized if MMF has not
    /// been initialized through MMF::init().
    pub(crate) fn remove_logged_module(module_id: &ModuleID) -> Result<(), FrameworkError> {
        let mut mmf_log_data_guard = MMF_LOG_DATA.write().expect(MMFPanic::MMFLogData_WriteLockPoisoned.message());
        let mmf_log_data = mmf_log_data_guard.as_mut().ok_or(FrameworkError::Framework_NotInitialized)?;
        mmf_log_data.logged_module_list.retain(|logged_module_id| logged_module_id != module_id);
        drop(mmf_log_data_guard);

        Ok(())
    }

    /// Generate a unique LogInstanceID.
    fn generate_log_instance_id() -> Result<u64, FrameworkError> {
        let current_id = MMF_LOG_INSTANCE_COUNTER.fetch_add(1, Ordering::Relaxed);
        if current_id == u64::MAX {
            return Err(FrameworkError::Logging_InstanceIDExhausted);
        }

        Ok(current_id)
    }

    /// Check whether logging is enabled for a module.
    pub(crate) fn must_log_module(module_id: &ModuleID) -> Result<bool, FrameworkError> {
        let log_mode = MMF_LOG_MODE.load(Ordering::Relaxed);

        if log_mode == LogMode::NoLog as u8 {
            return Ok(false);
        }

        if log_mode == LogMode::LogAll as u8 {
            return Ok(true);
        }

        if log_mode == LogMode::LogSelected as u8 {
            let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());
            let logging_data = mmf_log_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;
            return Ok(logging_data.logged_module_list.iter().any(|logged_module_id| logged_module_id == module_id));
        }

        // Invalid value => NoLog
        Ok(false)
    }

    /// Add a log event to MMFLog.
    ///
    /// If logging is disabled for the specified module,
    /// the event is silently ignored.
    ///
    /// Returns Framework_NotInitialized if MMF has
    /// not been initialized through MMF::init().
    pub(crate) fn add_log(action_start_timer: Instant, module_id: &ModuleID, log_action: LogAction, log_status: LogStatus) -> Result<(), FrameworkError> {
        // Skip immediately if logging is disabled
        // for this module.
        if !Self::must_log_module(module_id)? {
            return Ok(());
        }

        let log_instance_id = MMFLog::generate_log_instance_id()?;
        let timestamp_rfc3339 = MMF::get_timestamp_rfc3339();
        let duration_ms: Option<u128> = match log_status {
            LogStatus::Start => None,

            LogStatus::Ok | LogStatus::Error => Some(action_start_timer.elapsed().as_millis()),
        };

        let log_event = LogEvent { log_instance_id, timestamp_rfc3339, module_id: module_id.to_owned(), log_action, log_status, duration_ms };

        let mut mmf_log_data_guard = MMF_LOG_DATA.write().expect(MMFPanic::MMFLogData_WriteLockPoisoned.message());
        let logging_data = mmf_log_data_guard.as_mut().ok_or(FrameworkError::Framework_NotInitialized)?;

        // Write the log event to the log file if enabled.
        write_log_event(logging_data, &log_event)?;

        // Circular buffer behavior.
        if logging_data.log_event_list.len() >= logging_data.log_event_buffer_capacity {
            logging_data.log_event_list.pop_front();
        }
        logging_data.log_event_list.push_back(log_event);

        drop(mmf_log_data_guard);

        // Notify all waiters that a new log event
        // has been added to the buffer.
        MMF_LOG_NOTIFY.notify_waiters();

        Ok(())
    }

    /// Wait until new log events are available.
    ///
    /// If last_log_instance_id is None, all log
    /// events currently stored in MMFLog are returned.
    ///
    /// If last_log_instance_id is provided, only
    /// events with a greater LogInstanceID are
    /// returned.
    ///
    /// If matching log events are already present
    /// in the MMFLog buffer, they are returned
    /// immediately without waiting.
    ///
    /// Returns Framework_NotInitialized if MMFLog
    /// has not been initialized through MMF::init().
    pub async fn wait_log(last_log_instance_id: Option<LogInstanceID>) -> Result<LogList, FrameworkError> {
        loop {
            let log_list = MMFLog::get_log_list(last_log_instance_id)?;

            // New log events are already available.
            //
            // Return immediately without waiting for a
            // notification.
            if !log_list.log_event_list.is_empty() {
                return Ok(log_list);
            }

            // No new log event is currently available.
            //
            // Wait until MMFLog is notified that a new
            // log event has been added.
            MMF_LOG_NOTIFY.notified().await;
        }
    }

    /// Retrieve log events stored in MMFLog.
    ///
    /// If last_log_instance_id is None,
    /// all events currently present in the circular
    /// buffer are returned.
    ///
    /// If last_log_instance_id is provided,
    /// only events with a greater LogInstanceID are
    /// returned.
    ///
    /// missing_log_count indicates how many events
    /// could not be returned because they were overwritten
    /// in the circular buffer before being retrieved.
    ///
    /// Returns Framework_NotInitialized if MMFLog has
    /// not been initialized through MMF::init().
    fn get_log_list(last_log_instance_id: Option<LogInstanceID>) -> Result<LogList, FrameworkError> {
        let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());
        let mmf_log_data = mmf_log_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;

        // No log event is currently stored in MMFLog.
        if mmf_log_data.log_event_list.is_empty() {
            return Ok(LogList { first_log_instance_id: None, last_log_instance_id: None, missing_log_count: 0, log_event_list: Vec::new() });
        }

        // Retrieve the current boundaries of the circular buffer.
        //
        // The first and last LogInstanceID are used to detect
        // whether older events have been overwritten before
        // the caller could retrieve them.
        let first_log_event = mmf_log_data.log_event_list.front().expect(MMFPanic::LogBuffer_Inconsistency.message());
        let last_log_event = mmf_log_data.log_event_list.back().expect(MMFPanic::LogBuffer_Inconsistency.message());

        let first_buffer_log_instance_id = first_log_event.log_instance_id;
        let last_buffer_log_instance_id = last_log_event.log_instance_id;

        // Determine how many events were missed by the caller.
        //
        // Missing events occur when the caller requests events
        // older than the first LogInstanceID currently present
        // in the circular buffer.
        let missing_log_count = match last_log_instance_id {
            None => 0,

            Some(last_seen) => {
                if last_seen >= last_buffer_log_instance_id {
                    0
                } else if last_seen < first_buffer_log_instance_id {
                    first_buffer_log_instance_id.saturating_sub(last_seen + 1)
                } else {
                    0
                }
            }
        };

        // Return only the events that have not yet been
        // received by the caller.
        let log_event_list = match last_log_instance_id {
            None => mmf_log_data.log_event_list.iter().cloned().collect(),

            Some(last_seen) => mmf_log_data.log_event_list.iter().filter(|log_event| log_event.log_instance_id > last_seen).cloned().collect(),
        };

        Ok(LogList { first_log_instance_id: Some(first_buffer_log_instance_id), last_log_instance_id: Some(last_buffer_log_instance_id), missing_log_count, log_event_list })
    }

    /// Enables or disables MMF file logging.
    ///
    /// When enabled, every log event is immediately written to the log file
    /// and flushed to disk. This improves crash diagnostics, especially for
    /// native DLL failures, but introduces additional disk I/O and may reduce
    /// overall framework performance.
    pub fn set_log_file_enabled(enabled: bool) -> Result<(), FrameworkError> {
        let mut mmf_log_data_guard = MMF_LOG_DATA.write().expect(MMFPanic::MMFLogData_WriteLockPoisoned.message());

        let logging_data = mmf_log_data_guard.as_mut().ok_or(FrameworkError::Framework_NotInitialized)?;

        logging_data.log_file_enabled = enabled;

        Ok(())
    }

    /// Returns the current MMF log file path.
    pub fn get_log_file_path() -> Result<PathBuf, FrameworkError> {
        let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());

        let logging_data = mmf_log_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;

        Ok(logging_data.log_file_path.clone())
    }
}
