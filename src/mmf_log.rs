//! Public MMFLog (logging and observability) API.
//!
//! This API exposes the framework logging and observability
//! features.

use std::collections::VecDeque;
use std::sync::atomic::Ordering;
use std::time::Instant;
use chrono::{Utc, SecondsFormat};

use crate::mmf::{MMF_LOG_MODE, MMF_LOG_DATA, MMF_LOG_NOTIFY, MMF_LOG_INSTANCE_COUNTER};
use crate::framework_error::{FrameworkError, MMFPanic};
use crate::module::{ModuleID, EntityID};
use crate::message::MessageID;

/// Unique identifier assigned to each log event.
pub type LogInstanceID = u64;

/// Logging mode.
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogMode {

    /// Logging disabled.
    NoLog = 0,
    /// Log only selected modules.
    LogSelected = 1,
    /// Log all modules.
    LogAll = 2,
}

/// Log execution status.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LogStatus {

    Ok,
    Error,
}

/// Logged MMF action.
#[derive(Debug, Clone)]
pub enum LogAction {

    ModuleSpawn,
    ModuleInit,
    ModuleClose,
    ModuleAbort,
    ReceiveMessage {

        sender_id: EntityID,
        message_id: MessageID,
        priority: bool,
        wait_completion: bool,
    },
}

/// Single log event stored in MMFLog.
#[derive(Debug, Clone)]
pub struct LogEvent {

    /// Unique log identifier.
    pub log_instance_id: LogInstanceID,
    /// Event timestamp in RFC3339 format.
    pub timestamp_rfc3339: String,
    /// Module associated with the event.
    pub module_id: ModuleID,
    /// Logged action.
    pub log_action: LogAction,
    /// Action duration in milliseconds.
    pub duration_ms: u128,
    /// Final action status.
    pub log_status: LogStatus,
}

/// Internal MMFLog storage.
///
/// LoggingData maintains a circular buffer containing
/// the most recent logging events generated by MMF.
pub(crate) struct LoggingData {

    /// Maximum number of log events retained.
    pub(crate) log_event_buffer_capacity: usize,

    /// Selected modules when LogSelected is active.
    pub(crate) logged_module_list: Vec<ModuleID>,

    /// Circular buffer of log events.
    pub(crate) log_event_list: VecDeque<LogEvent>,
}

/// Timing information associated with a future log event.
///
/// LogTimer captures the timestamp at which an
/// operation starts as well as a monotonic timer
/// used later to measure its execution duration.
pub(crate) struct LogTimer {

    pub(crate) timestamp_rfc3339: String,
    pub(crate) start: Instant,
}

/// Result returned by MMFErr::get_log_list().
///
/// This structure contains the log events requested
/// by the caller together with metadata describing
/// the state of the circular buffer.
pub struct LogList {

    pub first_log_instance_id: Option<LogInstanceID>,

    pub last_log_instance_id: Option<LogInstanceID>,

    pub missing_log_count: u64,

    pub log_event_list: Vec<LogEvent>,
}


pub struct MMFLog;

/// Public MMFLog entry point.
impl MMFLog {

    /// Change the current MMF logging mode.
    ///
    /// When LogSelected is used, the provided module list
    /// replaces the previously configured selection.
    ///
    /// Returns Framework_NotInitialized if MMF has not
    /// been initialized through MMF::init().
    pub fn set_log_mode(log_mode: LogMode, logged_module_list: Option<Vec<ModuleID>>) -> Result<(), FrameworkError> {

        let mut mmf_log_data_guard = MMF_LOG_DATA.write().expect(MMFPanic::MMFLogData_WriteLockPoisoned.message());
        let mmf_log_data = mmf_log_data_guard.as_mut().ok_or(FrameworkError::Framework_NotInitialized)?;
        
        MMF_LOG_MODE.store(log_mode as u8, Ordering::Relaxed);

        if let Some(logged_module_list) = logged_module_list {

            mmf_log_data.logged_module_list = logged_module_list;
        }

        drop(mmf_log_data_guard);
        Ok(())
    }


    /// Retrieve the current MMF logging mode.
    ///
    /// Returns Framework_NotInitialized if MMF has not
    /// been initialized through MMF::init().
    pub fn get_log_mode() -> Result<LogMode, FrameworkError> {

        let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());
        
        if mmf_log_data_guard.is_none() {

            return Err(FrameworkError::Framework_NotInitialized);
        }

        let log_mode = match MMF_LOG_MODE.load(Ordering::Relaxed) {

                0 => LogMode::NoLog,
                1 => LogMode::LogAll,
                2 => LogMode::LogSelected,
                // Invalid value => NoLog
                _ => LogMode::NoLog,
            };

        drop(mmf_log_data_guard);
        Ok(log_mode)
    }


    /// Retrieve the currently selected module list.
    ///
    /// Returns Framework_NotInitialized if MMF has not
    /// been initialized through MMF::init().
    pub fn get_logged_module_list() -> Result<Vec<ModuleID>, FrameworkError> {

        let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());
        let mmf_log_data = mmf_log_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;
        let logged_module_list = mmf_log_data.logged_module_list.clone();

        drop(mmf_log_data_guard);
        Ok(logged_module_list)
    }


    /// Generate a unique ErrorInstanceID.
    fn generate_log_instance_id() -> Result<u64, FrameworkError> {

        let current_id = MMF_LOG_INSTANCE_COUNTER.fetch_add(1, Ordering::Relaxed);
        if current_id == u64::MAX {
            return Err(FrameworkError::Error_InstanceIDExhausted);
        }

        Ok(current_id)
    }


    /// Check whether logging is enabled for a module.
    pub(crate) fn must_log_module(module_id: &ModuleID) -> Result<bool, FrameworkError> {

        let log_mode = MMF_LOG_MODE.load(Ordering::Relaxed);

        if log_mode == LogMode::NoLog as u8 {

            return Ok(false);
        }

        if log_mode == LogMode::LogAll as u8 {

            return Ok(true);
        }

        if log_mode == LogMode::LogSelected as u8 {

            let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());
            let logging_data = mmf_log_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;
            return Ok(logging_data.logged_module_list.contains(module_id));
        }

        // Invalid value => NoLog
        Ok(false)
    }


    /// Start a new log timer.
    ///
    /// The returned LogTimer stores the current
    /// RFC3339 timestamp and a monotonic timer that
    /// can later be passed to MMFLog::add_log().
    pub(crate) fn start_log_timer() -> LogTimer {

        LogTimer {

            timestamp_rfc3339:Utc::now().to_rfc3339_opts(SecondsFormat::Millis, true), 
            start: Instant::now(),
                   }
    }


    /// Add a log event to MMFLog.
    ///
    /// If logging is disabled for the specified module,
    /// the event is silently ignored.
    ///
    /// Returns Framework_NotInitialized if MMF has
    /// not been initialized through MMF::init().
    pub(crate) fn add_log(log_timer: LogTimer, module_id: &ModuleID, log_action: LogAction, log_status: LogStatus) -> Result<(), FrameworkError> {

        // Skip immediately if logging is disabled
        // for this module.
        if !Self::must_log_module(&module_id)? {
            return Ok(());
        }

        let log_instance_id = MMFLog::generate_log_instance_id()?;
        let duration_ms = log_timer.start.elapsed().as_millis();
        let log_event = LogEvent {

            log_instance_id,
            timestamp_rfc3339: log_timer.timestamp_rfc3339,
            module_id: module_id.clone(),
            log_action,
            duration_ms,
            log_status,
        };

        let mut mmf_log_data_guard = MMF_LOG_DATA.write().expect(MMFPanic::MMFLogData_WriteLockPoisoned.message());
        let logging_data = mmf_log_data_guard.as_mut().ok_or(FrameworkError::Framework_NotInitialized)?;

        // Circular buffer behavior.
        if logging_data.log_event_list.len() >= logging_data.log_event_buffer_capacity {

            logging_data.log_event_list.pop_front();
        }

        logging_data.log_event_list.push_back(log_event);

        drop(mmf_log_data_guard);

        // Notify all waiters that a new log event
        // has been added to the buffer.
        MMF_LOG_NOTIFY.notify_waiters();

        Ok(())
    }


    /// Wait until new log events are available.
    ///
    /// If last_log_instance_id is None, all log
    /// events currently stored in MMFLog are returned.
    ///
    /// If last_log_instance_id is provided, only
    /// events with a greater LogInstanceID are
    /// returned.
    ///
    /// If matching log events are already present
    /// in the MMFLog buffer, they are returned
    /// immediately without waiting.
    ///
    /// Returns Framework_NotInitialized if MMFLog
    /// has not been initialized through MMF::init().
    pub async fn wait_log(last_log_instance_id: Option<LogInstanceID>) -> Result<LogList, FrameworkError> {

        loop {

            let log_list = MMFLog::get_log_list(last_log_instance_id)?;

            // New log events are already available.
            //
            // Return immediately without waiting for a
            // notification.
            if !log_list.log_event_list.is_empty() {

                return Ok(log_list);
            }

            // No new log event is currently available.
            //
            // Wait until MMFLog is notified that a new
            // log event has been added.
            MMF_LOG_NOTIFY.notified().await;
        }
    }


    /// Retrieve log events stored in MMFLog.
    ///
    /// If last_log_instance_id is None,
    /// all events currently present in the circular
    /// buffer are returned.
    ///
    /// If last_log_instance_id is provided,
    /// only events with a greater LogInstanceID are
    /// returned.
    ///
    /// missing_log_count indicates how many events
    /// could not be returned because they were overwritten
    /// in the circular buffer before being retrieved.
    ///
    /// Returns Framework_NotInitialized if MMFLog has
    /// not been initialized through MMF::init().
    fn get_log_list(last_log_instance_id: Option<LogInstanceID>) -> Result<LogList, FrameworkError> {

        let mmf_log_data_guard = MMF_LOG_DATA.read().expect(MMFPanic::MMFLogData_ReadLockPoisoned.message());
        let mmf_log_data = mmf_log_data_guard.as_ref().ok_or(FrameworkError::Framework_NotInitialized)?;

        // No log event is currently stored in MMFLog.
        if mmf_log_data.log_event_list.is_empty() {

            return Ok(
                LogList {

                    first_log_instance_id: None,
                    last_log_instance_id: None,
                    missing_log_count: 0,
                    log_event_list: Vec::new(),
                }
            );
        }

        // Retrieve the current boundaries of the circular buffer.
        //
        // The first and last LogInstanceID are used to detect
        // whether older events have been overwritten before
        // the caller could retrieve them.
        let first_log_event = mmf_log_data.log_event_list.front().expect(MMFPanic::LogBuffer_Inconsistency.message());
        let last_log_event = mmf_log_data.log_event_list.back().expect(MMFPanic::LogBuffer_Inconsistency.message());

        let first_buffer_log_instance_id = first_log_event.log_instance_id;
        let last_buffer_log_instance_id = last_log_event.log_instance_id;

        // Determine how many events were missed by the caller.
        //
        // Missing events occur when the caller requests events
        // older than the first LogInstanceID currently present
        // in the circular buffer.
        let missing_log_count = match last_log_instance_id {

            None => 0,

            Some(last_seen) => {

                if last_seen >= last_buffer_log_instance_id {
                    0
                } else if last_seen < first_buffer_log_instance_id {
                    first_buffer_log_instance_id.saturating_sub(last_seen + 1)
                } else {
                    0
                }
            }
        };

        // Return only the events that have not yet been
        // received by the caller.
        let log_event_list = match last_log_instance_id {

            None => {

                mmf_log_data.log_event_list.iter().cloned().collect()
            }

            Some(last_seen) => {

                mmf_log_data.log_event_list.iter().filter(|log_event| {
                        log_event.log_instance_id > last_seen
                    }).cloned().collect()
            }
        };
                
        Ok(
            LogList {

                first_log_instance_id: Some(first_buffer_log_instance_id),
                last_log_instance_id: Some(last_buffer_log_instance_id),
                missing_log_count,
                log_event_list,
            }
        )
    }    

}